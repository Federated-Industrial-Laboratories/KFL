/* policy_fixture.h - trained-framework policies and the actions they
 * produce, for the agreement arm of test_rl_policy.
 *
 * A policy file that round-trips its own bytes and then computes a
 * different action is worse than useless, so the gate holds the
 * evaluator against the framework that produced the weights, not
 * only against itself. These arrays are that reference, and they are
 * data rather than a live dependency: the gate needs no training
 * package installed to run the comparison.
 *
 * Each entry is a small feedforward policy over 13 observation
 * channels and 15 action channels, with hidden layers of 8 and 4 units,
 * exported through the package's own writer and therefore also a
 * check that the writer and the reader agree on every byte of the
 * layout. The observations
 * are real states taken from a compiled world's own stream, and the
 * expected actions are what the producing framework returned for
 * them with deterministic prediction. The first two entries differ in
 * hidden activation so that one activation cannot stand in for the
 * other.
 *
 * The third entry carries the first one's weights over a world of 26
 * observation channels in which every channel a policy reads has a
 * ground-truth channel beside it: it reads the 13 even-numbered ones
 * and names them channel by channel, so no offset and width
 * describes them. Its expected actions are POLICY_FIXTURE_TANH_ACTIONS,
 * because the values reaching the network are the same 13 numbers in
 * the same order. An evaluator that gathered a contiguous run
 * instead would feed it the ground truth beside each measurement and
 * disagree at once.
 *
 * The blobs were re-encoded from the exported ones when the format
 * gained its channel list. Every weight, statistic and bound is the
 * same bit pattern it was exported as, which is why the expected
 * actions below are unchanged and still the producing framework's
 * own.
 *
 * The expected actions were computed in binary32 and this library
 * evaluates in binary64, so they agree to about a part in ten
 * million rather than exactly; POLICY_FIXTURE_TOLERANCE is set well
 * inside the margin that separates that from any real defect, since
 * a transposed matrix, a reversed layer order, a dropped
 * standardisation or a missing clamp all move an action by order one.
 *
 * Produced by torch 2.13.0 and stable-baselines3 2.9.0.
 * Regenerating the weights needs both; re-encoding them into a later
 * layout needs only the package's writer, and running the gate needs
 * neither.
 */
